if PREPEND_EARLY_GAPS:
    # Sanity check: within consecutive runs, buffer must grow by exactly the
    # episode's step count. Catches transcription mistakes.
    known = sorted(set(real) | {476})
    for a, b in zip(known, known[1:]):
        if 476 in (a, b):
            continue
        if b == a + 1:
            diff = real[b][3] - real[a][3]
            if diff != real[b][2]:
                print(f"WARNING: ep {b}: buffer diff {diff} != steps {real[b][2]}")

    # Anchor from the existing log (first real episode we have on disk)
    import re
    pat = re.compile(r"Episode\s+(\d+)\s+\|\s+Score:\s+(-?\d+\.?\d*)\s+\|\s+Epsilon:\s+([\d.]+)\s+\|\s+Steps:\s+(\d+)\s+\|\s+Buffer:\s+(\d+)\s+\|\s+Time:\s+([\d.]+)s")
    with open(LOG_PATH, encoding="utf-8") as f:
        for line in f:
            m = pat.search(line)
            if m:
                anchor_ep = int(m.group(1))
                anchor = (float(m.group(2)), float(m.group(3)), int(m.group(4)),
                          int(m.group(5)), float(m.group(6)))
                break
    print(f"Anchor episode {anchor_ep}: {anchor}")
    assert anchor_ep == 476

    # Fill every missing episode from 1 to anchor-1 by linear interpolation
    def fmt(ep, score, eps_, steps, buf, t, filled):
        line = (f"Episode {ep:5d} | Score: {score:5.1f} | Epsilon: {eps_:.3f} | "
                f"Steps: {steps} | Buffer: {buf} | Time: {t:.2f}s")
        return line + (" | Filled(avg)" if filled else "")

    lines = []
    for ep in range(1, anchor_ep):
        if ep in real:
            s, e, st, b, t = real[ep]
            lines.append(fmt(ep, s, e, st, b, t, False))
        else:
            lo = max(k for k in known if k < ep)
            hi = min(k for k in known if k > ep)
            get = lambda k: real[k] if k in real else anchor
            slo, shi = get(lo), get(hi)
            frac = (ep - lo) / (hi - lo)
            vals = tuple(round(a + (b - a) * frac, 4) for a, b in zip(slo, shi))
            score, eps_, st, b, t = vals
            lines.append(fmt(ep, score, eps_, int(round(st)), int(round(b)), t, True))

    with open(NEW_LINES_PATH, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")

    with open(LOG_PATH, encoding="utf-8") as f:
        original = f.read()

    with open(LOG_PATH, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
        f.write(original)

    n_filled = sum("Filled" in l for l in lines)
    print(f"Prepended {len(lines)} episodes ({len(lines) - n_filled} real, "
          f"{n_filled} gap-filled) to {LOG_PATH}")
